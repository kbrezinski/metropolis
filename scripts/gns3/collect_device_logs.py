#!/usr/bin/env python3
"""Follow GNS3 Docker-node logs into an experiment run directory."""

from __future__ import annotations

import argparse
import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import urlsplit

from _cli import DATASET, add_server_arguments, connect, load_documents
from device_logs import DeviceLogCollector

RUN_ID = re.compile(r"^[A-Za-z0-9_-]+$")


def docker_host_mapping(values: list[str]) -> dict[str, str]:
    mapping = {}
    for value in values:
        compute_id, separator, host = value.partition("=")
        parsed = urlsplit(host)
        if (
            not separator
            or not compute_id
            or parsed.scheme not in {"ssh", "unix", "npipe"}
            or parsed.password is not None
            or (parsed.scheme == "ssh" and not parsed.hostname)
        ):
            raise ValueError(
                "--docker-host must be COMPUTE_ID=ssh://user@host, unix://path, "
                "or npipe://path (no password in the URI)"
            )
        mapping[compute_id] = host
    return mapping


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    add_server_arguments(parser)
    parser.add_argument("--dataset", type=Path, default=DATASET)
    parser.add_argument(
        "--run-id", help="Safe unique run identifier; generated by default"
    )
    parser.add_argument("--duration", type=float, default=300.0)
    parser.add_argument(
        "--docker-host",
        action="append",
        default=[],
        metavar="COMPUTE_ID=URI",
        help="Docker engine on the node's GNS3 compute; repeat for each compute",
    )
    parser.add_argument("--docker-binary", default="docker")
    args = parser.parse_args()
    if args.duration <= 0:
        parser.error("--duration must be positive")
    run_id = (
        args.run_id or datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ") + "_logs"
    )
    if not RUN_ID.fullmatch(run_id):
        parser.error(
            "--run-id may contain only letters, digits, underscores and hyphens"
        )
    try:
        hosts = docker_host_mapping(args.docker_host)
    except ValueError as exc:
        parser.error(str(exc))
    dataset = args.dataset.resolve()
    address_plan, inventory, infrastructure, _ = load_documents(dataset)
    client = connect(args)
    project = client.project_by_name(args.project)
    if project is None:
        print(f"error: no project named {args.project} on this server", file=sys.stderr)
        return 2
    run_dir = dataset / "runs" / run_id
    try:
        collector = DeviceLogCollector(
            client,
            project.project_id,
            run_dir,
            run_id,
            hosts,
            metadata={
                "testbed_id": address_plan["testbed_id"],
                "dataset_version": dataset.name,
                "dataset_path": str(dataset),
                "project_name": project.name,
                "timeline_path": "timeline.jsonl",
                "captures": [],
            },
            expected_syslog_sources=[
                router["name"] for router in infrastructure["routers"]
            ],
            expected_switch_syslog_sources=[
                switch["name"]
                for group in ("switches", "segments")
                for switch in infrastructure.get(group, [])
            ],
            silent_sources=[
                device["name"]
                for device in inventory["devices"]
                if device["image"] == "metropolis/reachability-probe:dev"
            ],
            docker_binary=args.docker_binary,
        )
    except FileExistsError:
        print(f"error: run directory already exists: {run_dir}", file=sys.stderr)
        return 2
    manifest = collector.run(args.duration)
    print(
        json.dumps(
            {
                "run_dir": str(run_dir),
                "status": manifest["status"],
                "sources": len(manifest["logs"]["sources"]),
                "failures": manifest["failures"],
            },
            indent=2,
        )
    )
    return 0 if manifest["status"] == "complete" else 1


if __name__ == "__main__":
    raise SystemExit(main())
