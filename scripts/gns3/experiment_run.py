#!/usr/bin/env python3
"""Run a shared-ID capture, log, and resource monitoring experiment."""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import os
import re
import sys
import uuid
from datetime import datetime, timezone
from pathlib import Path

from _cli import (
    DATASET,
    add_server_arguments,
    connect,
    load_documents,
    template_name_by_image,
)
from collect_device_logs import docker_host_mapping
from experiment import run_experiment
from firewall_policy import compile_policy, parse_attack_exception
from router_config import DEFAULT_PASSWORD, DEFAULT_USERNAME
from run_profiles import load_profile
from baseline_config import BASELINE_FILE, load_baseline
from rdp_run import declared_rdp
from topology import build_plan

RUN_ID = re.compile(r"^[A-Za-z0-9_-]+$")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    add_server_arguments(parser)
    parser.add_argument("--dataset", type=Path, default=DATASET)
    parser.add_argument("--run-id", help="Unique run identifier; generated by default")
    parser.add_argument("--duration", type=float, default=60.0)
    parser.add_argument("--profile", type=Path, help="Opt-in device/link profile YAML")
    parser.add_argument(
        "--rdp-udp-amplify",
        action="append",
        default=[],
        metavar="NODE",
        help="Temporarily amplify synthetic UDP 3389 replies on a declared RDP server; repeatable",
    )
    parser.add_argument(
        "--metrics-interval",
        type=float,
        default=5.0,
        help="CPU/RAM sampling interval in seconds (default: 5)",
    )
    parser.add_argument(
        "--no-metrics", action="store_true", help="Disable resource and traffic reports"
    )
    parser.add_argument(
        "--start-lab", action="store_true", help="Start nodes after telemetry begins"
    )
    parser.add_argument(
        "--configure-routers",
        action="store_true",
        help="Push VyOS scripts after startup",
    )
    parser.add_argument("--router-username", default=DEFAULT_USERNAME)
    parser.add_argument("--startup-timeout", type=float, default=120.0)
    parser.add_argument(
        "--attack-allow",
        action="append",
        default=[],
        metavar="SOURCE-NET:DEST-NET:PROTOCOL:PORT",
        help="Temporarily permit one attack-lab source CIDR to a destination CIDR; repeat as needed",
    )
    parser.add_argument(
        "--links", nargs="+", help="Declared PCAP links; default is all built links"
    )
    parser.add_argument(
        "--docker-host",
        action="append",
        default=[],
        metavar="COMPUTE_ID=URI",
        help="Docker engine on each node's GNS3 compute; repeat for each compute",
    )
    args = parser.parse_args()
    if not math.isfinite(args.metrics_interval) or args.metrics_interval <= 0:
        parser.error("--metrics-interval must be positive and finite")
    if args.duration <= 0 or args.startup_timeout <= 0:
        parser.error("duration and startup timeout must be positive")
    if args.attack_allow and not args.configure_routers:
        parser.error("--attack-allow requires --configure-routers")
    run_id = args.run_id or (
        datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
        + "_"
        + uuid.uuid4().hex[:8]
    )
    if not RUN_ID.fullmatch(run_id):
        parser.error(
            "--run-id may contain only letters, digits, underscores and hyphens"
        )
    try:
        hosts = docker_host_mapping(args.docker_host)
    except ValueError as exc:
        parser.error(str(exc))
    dataset = args.dataset.resolve()
    address_plan, inventory, infrastructure, link_plan = load_documents(dataset)
    try:
        declared_rdp(inventory, args.rdp_udp_amplify)
    except ValueError as exc:
        parser.error(f"RDP: {exc}")
    baseline = None
    baseline_path = dataset / BASELINE_FILE
    if baseline_path.is_file():
        try:
            baseline = load_baseline(baseline_path, inventory, infrastructure)
        except (ValueError, OSError) as exc:
            parser.error(f"baseline: {exc}")
    profile = None
    if args.profile is not None:
        try:
            profile = load_profile(args.profile, inventory, infrastructure, link_plan)
            profile["path"] = str(args.profile.resolve())
            profile["sha256"] = hashlib.sha256(args.profile.read_bytes()).hexdigest()
        except (ValueError, OSError) as exc:
            parser.error(f"profile: {exc}")
    try:
        exceptions = [parse_attack_exception(value) for value in args.attack_allow]
        firewall_commands, firewall_report = compile_policy(
            dataset, infrastructure, inventory, exceptions
        )
        baseline_firewall_commands, _ = compile_policy(
            dataset, infrastructure, inventory
        )
    except (ValueError, KeyError, FileNotFoundError) as exc:
        parser.error(f"firewall policy: {exc}")
    declared = {link["id"] for link in link_plan["links"]}
    unknown = set(args.links or []) - declared
    if unknown:
        parser.error(f"unknown declared link(s): {', '.join(sorted(unknown))}")
    client = connect(args)
    project = client.project_by_name(args.project)
    if project is None:
        print(f"error: no project named {args.project} on this server", file=sys.stderr)
        return 2
    topology = build_plan(
        inventory, infrastructure, link_plan, template_name_by_image()
    )
    files = (
        dataset / "topology/address-plan.yaml",
        dataset / "topology/links.yaml",
        dataset / "device_instances/initial_devices.yaml",
        dataset / "device_instances/infrastructure.yaml",
    )
    metadata = {
        "testbed_id": address_plan["testbed_id"],
        "dataset_version": dataset.name,
        "dataset_path": str(dataset),
        "project_name": project.name,
        "topology_document_sha256": {
            str(path.relative_to(dataset)): hashlib.sha256(
                path.read_bytes()
            ).hexdigest()
            for path in files
        },
        "firewall_policy_sha256": hashlib.sha256(
            (dataset / "topology/firewall-policy.yaml").read_bytes()
        ).hexdigest(),
    }
    try:
        manifest = run_experiment(
            client,
            project,
            topology,
            inventory,
            infrastructure,
            link_plan,
            dataset,
            run_id,
            args.duration,
            hosts,
            selected_links=args.links,
            start_lab=args.start_lab,
            configure_routers=args.configure_routers,
            firewall_commands=firewall_commands,
            baseline_firewall_commands=baseline_firewall_commands,
            firewall_exceptions=firewall_report["attack_exceptions"],
            router_username=args.router_username,
            router_password=os.environ.get(
                "METROPOLIS_ROUTER_PASSWORD", DEFAULT_PASSWORD
            ),
            startup_timeout=args.startup_timeout,
            metadata=metadata,
            metrics_enabled=not args.no_metrics,
            metrics_interval=args.metrics_interval,
            profile=profile,
            baseline=baseline,
            rdp_udp_amplify=args.rdp_udp_amplify,
        )
    except FileExistsError:
        print(f"error: run ID already exists: {run_id}", file=sys.stderr)
        return 2
    report = {
        "run_id": run_id,
        "status": manifest["status"],
        "run_manifest": str(dataset / "runs" / run_id / "manifest.json"),
        "capture_manifests": manifest["captures"],
        "failures": manifest["failures"],
    }
    if "resource_baseline" in manifest:
        report["baseline_status"] = manifest["resource_baseline"]["status"]
    print(json.dumps(report, indent=2))
    return 0 if manifest["status"] == "complete" else 1


if __name__ == "__main__":
    raise SystemExit(main())
