#!/usr/bin/env python3
"""Run a shared-ID PCAP, Docker log, and router syslog experiment."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sys
import uuid
from datetime import datetime, timezone
from pathlib import Path

from _cli import (
    DATASET,
    add_server_arguments,
    connect,
    load_documents,
    template_name_by_image,
)
from collect_device_logs import docker_host_mapping
from experiment import run_experiment
from router_config import DEFAULT_PASSWORD, DEFAULT_USERNAME
from topology import build_plan

RUN_ID = re.compile(r"^[A-Za-z0-9_-]+$")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    add_server_arguments(parser)
    parser.add_argument("--dataset", type=Path, default=DATASET)
    parser.add_argument("--run-id", help="Unique run identifier; generated by default")
    parser.add_argument("--duration", type=float, default=60.0)
    parser.add_argument(
        "--start-lab", action="store_true", help="Start nodes after telemetry begins"
    )
    parser.add_argument(
        "--configure-routers",
        action="store_true",
        help="Push VyOS scripts after startup",
    )
    parser.add_argument("--router-username", default=DEFAULT_USERNAME)
    parser.add_argument("--startup-timeout", type=float, default=120.0)
    parser.add_argument(
        "--links", nargs="+", help="Declared PCAP links; default is all built links"
    )
    parser.add_argument(
        "--docker-host",
        action="append",
        default=[],
        metavar="COMPUTE_ID=URI",
        help="Docker engine on each node's GNS3 compute; repeat for each compute",
    )
    args = parser.parse_args()
    if args.duration <= 0 or args.startup_timeout <= 0:
        parser.error("duration and startup timeout must be positive")
    run_id = args.run_id or (
        datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
        + "_"
        + uuid.uuid4().hex[:8]
    )
    if not RUN_ID.fullmatch(run_id):
        parser.error(
            "--run-id may contain only letters, digits, underscores and hyphens"
        )
    try:
        hosts = docker_host_mapping(args.docker_host)
    except ValueError as exc:
        parser.error(str(exc))
    dataset = args.dataset.resolve()
    address_plan, inventory, infrastructure, link_plan = load_documents(dataset)
    declared = {link["id"] for link in link_plan["links"]}
    unknown = set(args.links or []) - declared
    if unknown:
        parser.error(f"unknown declared link(s): {', '.join(sorted(unknown))}")
    client = connect(args)
    project = client.project_by_name(args.project)
    if project is None:
        print(f"error: no project named {args.project} on this server", file=sys.stderr)
        return 2
    topology = build_plan(
        inventory, infrastructure, link_plan, template_name_by_image()
    )
    files = (
        dataset / "topology/address-plan.yaml",
        dataset / "topology/links.yaml",
        dataset / "device_instances/initial_devices.yaml",
        dataset / "device_instances/infrastructure.yaml",
    )
    metadata = {
        "testbed_id": address_plan["testbed_id"],
        "dataset_version": dataset.name,
        "dataset_path": str(dataset),
        "project_name": project.name,
        "topology_document_sha256": {
            str(path.relative_to(dataset)): hashlib.sha256(
                path.read_bytes()
            ).hexdigest()
            for path in files
        },
    }
    try:
        manifest = run_experiment(
            client,
            project,
            topology,
            inventory,
            infrastructure,
            link_plan,
            dataset,
            run_id,
            args.duration,
            hosts,
            selected_links=args.links,
            start_lab=args.start_lab,
            configure_routers=args.configure_routers,
            router_username=args.router_username,
            router_password=os.environ.get(
                "METROPOLIS_ROUTER_PASSWORD", DEFAULT_PASSWORD
            ),
            startup_timeout=args.startup_timeout,
            metadata=metadata,
        )
    except FileExistsError:
        print(f"error: run ID already exists: {run_id}", file=sys.stderr)
        return 2
    print(
        json.dumps(
            {
                "run_id": run_id,
                "status": manifest["status"],
                "run_manifest": str(dataset / "runs" / run_id / "manifest.json"),
                "capture_manifests": manifest["captures"],
                "failures": manifest["failures"],
            },
            indent=2,
        )
    )
    return 0 if manifest["status"] == "complete" else 1


if __name__ == "__main__":
    raise SystemExit(main())
